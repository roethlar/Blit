#!/usr/bin/env python3
"""Write `crates/blit-core/src/find_name/reference_classes.rs`: the character
classes `blit find -name '[[:class:]]'` matches by.

They are the classes of GNU find's reference locale, `C.UTF-8`, read from THIS
machine's C library for every code point — the ones a character is assigned
to and the ones none is. Run it on a Linux machine with glibc where the
reference moves (a C library with newer Unicode tables), then `cargo fmt` and
the tests: `find_name::tests::the_reference_tables_are_whole` pins the counts
written here, and `the_classes_are_the_c_librarys_under_c_utf8` compares the
tables with the library again.

Usage: scripts/gen_find_classes.py [OUT.rs]
"""
import ctypes
import ctypes.util
import pathlib
import sys

OUT = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else (
    pathlib.Path(__file__).resolve().parent.parent
    / "crates/blit-core/src/find_name/reference_classes.rs"
)
# The classes kept as tables. The other eight are these and a few fixed
# code points: see `Unit for char` in `find_name.rs`.
TABLES = ["alpha", "upper", "lower", "print"]

libc = ctypes.CDLL(ctypes.util.find_library("c"), use_errno=True)
libc.setlocale.restype = ctypes.c_char_p
LC_ALL = 6
assert libc.setlocale(LC_ALL, b"C.UTF-8"), "this machine has no C.UTF-8 locale"
libc.wctype.restype = ctypes.c_ulong
libc.wctype.argtypes = [ctypes.c_char_p]
libc.iswctype.argtypes = [ctypes.c_uint, ctypes.c_ulong]
libc.gnu_get_libc_version.restype = ctypes.c_char_p
version = "glibc " + libc.gnu_get_libc_version().decode()


def edges(name):
    """The code points at which membership of `name` changes, in order."""
    kind = libc.wctype(name.encode())
    found, inside, members = [], False, 0
    for point in range(0x110000):
        member = not 0xD800 <= point <= 0xDFFF and bool(libc.iswctype(point, kind))
        members += member
        if member != inside:
            found.append(point)
            inside = member
    if inside:
        found.append(0x110000)
    return found, members


lines = [
    "//! The character classes of `find`'s reference locale, `C.UTF-8`, as the C",
    "//! library has them, for every code point — the ones no character is",
    "//! assigned to among them.",
    "//!",
    "//! GENERATED by `scripts/gen_find_classes.py`; do not edit. Run it where",
    "//! the reference moves.",
    "//!",
    "//! Each table is the code points at which membership changes, in order:",
    "//! a code point is in the class when an odd number of them are at or",
    "//! below it.",
    "",
    "/// The C library the tables were read from.",
    "#[cfg(test)]",
    f'pub(super) const READ_FROM: &str = "{version}";',
]
for name in TABLES:
    table, members = edges(name)
    assert len(table) % 2 == 0
    lines += [
        "",
        f"/// How many code points `[:{name}:]` holds.",
        "#[cfg(test)]",
        f"pub(super) const {name.upper()}_MEMBERS: u32 = {members};",
        f"/// `[:{name}:]`, in {len(table) // 2} runs.",
        f"pub(super) static {name.upper()}: [u32; {len(table)}] = [",
        "    " + ", ".join(f"{point:#x}" for point in table) + ",",
        "];",
    ]
    print(f"{name}: {members} code points, {len(table) // 2} runs")
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT} from {version}; now run `cargo fmt`")
